import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(
  repoRoot,
  'services/loom-demo/src/generated/receiptFixtures.ts',
);

const fixtures = [
  ['PRIMARY_DRAND_RECEIPT', 'goldens/golden_receipt_03_d20_drand.json'],
  ['TAMPERED_DRAND_RECEIPT', 'goldens/golden_receipt_04_d20_drand_tampered_sig.json'],
  ['LEGACY_RECEIPT', 'goldens/golden_receipt_01_d20.json'],
];

const lines = [
  '// Generated by scripts/generate-browser-fixtures.mjs from committed goldens.',
  '// Do not edit this file directly.',
  '',
];

for (const [name, relativePath] of fixtures) {
  const sourcePath = resolve(repoRoot, relativePath);
  const text = await readFile(sourcePath, 'utf8');
  JSON.parse(text);
  const hash = createHash('sha256').update(text).digest('hex');
  lines.push(`export const ${name} = ${JSON.stringify(text)};`);
  lines.push(`export const ${name}_SHA256 = '${hash}';`);
  lines.push('');
}

const generated = `${lines.join('\n')}\n`;
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    // A missing generated file is a mismatch.
  }
  if (current !== generated) {
    console.error('browser receipt fixtures do not match committed goldens');
    console.error('run: node scripts/generate-browser-fixtures.mjs');
    process.exit(1);
  }
  console.log('browser receipt fixtures match committed goldens');
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated, 'utf8');
  console.log(`wrote ${outputPath}`);
}
