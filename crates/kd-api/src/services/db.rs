pub async fn insert_transcript_meta(
    pg: &PgPool,
    roll_id: i64,
    s3_key: &str,
    sha256: &[u8],
    size_bytes: i64,
) -> Result<(), sqlx::Error> {
    sqlx::query!(
        r#"INSERT INTO transcripts_meta (roll_id, s3_key, sha256, size_bytes)
           VALUES ($1, $2, $3, $4)"#,
        roll_id,
        s3_key,
        sha256,
        size_bytes
    )
    .execute(pg)
    .await?;
    Ok(())
}
